package ExerciciosLoop;

public class Exercicio06 {
    static void main(String[] args) {
        //Usando while
        System.out.printf("%n");
        //Usando for
        for (int i = 1; i <= 50; i++) {
            if (i % 2 != 0) {
                System.out.println(i);
            }
        }
    }
}
