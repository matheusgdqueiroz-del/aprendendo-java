package ExerciciosLoop;

public class Exercicio01 {
    static void main(String[] args) {

        //Usando while
        int contador = 1;
        while(contador <=10) {
            System.out.print(contador + " ");
            contador++;
        }
        System.out.printf("%n");
        //Usando for
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }

    }
}
