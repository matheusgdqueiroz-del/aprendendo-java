package basico;

public class OperadoresParte01 {
    static void main(String[] args) {

        int numero01 = 200;
        int numero02 = 120;
        int soma = numero01 + numero02;

        double primeiroNumero = 10;
        double segundoNumero = 20;
        double divisao = primeiroNumero / segundoNumero;

        System.out.println("A soma dos números é igual a: " + soma);
        System.out.println("A divisão dos números é: " + divisao );
    }
}

