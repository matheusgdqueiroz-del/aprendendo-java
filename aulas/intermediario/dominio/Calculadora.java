package intermediario.dominio;

public class Calculadora {
    public void soma(int x, int y) {
        System.out.println(x + y);
    }
    public void subtracao(int x, int y) {
        System.out.println(x - y);
    }
    public void multiplicacao(int x, int y) {
        System.out.println(x * y);
    }
}
